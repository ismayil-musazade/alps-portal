/** Install or refresh the paper. Safe to run repeatedly. */
export async function installDemoPaper(db: PrismaClient | typeof defaultDb = defaultDb) {
  const existing = await db.testPaper.findFirst({ where: { title: SLUG_TITLE } });

  const paper = existing
    ? await db.testPaper.update({
        where: { id: existing.id },
        data: { status: "PUBLISHED", durationMin: 10, passScore: 3 },
      })
    : await db.testPaper.create({
        data: {
          title: SLUG_TITLE,
          courseType: "SAT",
          subject: "Reading & Writing",
          description: "Five passage-based questions. Used to place a newcomer before they enrol.",
          durationMin: 10,
          passScore: 3,
          status: "PUBLISHED",
        },
      });

  await db.testQuestion.deleteMany({ where: { paperId: paper.id } });
  await db.testQuestion.createMany({
    data: QUESTIONS.map((q, i) => ({
      paperId: paper.id,
      order: i + 1,
      section: q.section,
      type: "SINGLE_CHOICE" as const,
      passage: q.passage,
      prompt: q.prompt,
      options: q.options,
      answer: q.answer,
      points: 1,
    })),
  });

  return { id: paper.id, title: paper.title, questions: QUESTIONS.length };
}
